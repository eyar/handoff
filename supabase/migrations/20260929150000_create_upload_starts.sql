-- Detect Shortcut uploads that are abandoned before they reach shortcut-upload.
-- The Supabase gateway receives the whole request body before the function runs,
-- so an upload the phone gives up on (stop button, app switch, network drop)
-- never reaches us. The Shortcut therefore sends a small "upload_start" ping
-- first; shortcut-upload records it here and marks it arrived when the upload
-- with the same id comes in. cleanup-storage flags pings that never arrived and
-- purges rows after 48 hours. No file names are stored.

CREATE TABLE IF NOT EXISTS public.upload_starts (
  id TEXT PRIMARY KEY, -- random id generated by the Shortcut, sent again as x-upload-id
  size BIGINT,
  target TEXT NOT NULL, -- 'room' or 'staged'
  room_id VARCHAR(10),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  arrived_at TIMESTAMPTZ,
  abandoned_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_upload_starts_created_at ON public.upload_starts (created_at);

-- RLS on with no policies: only the service role (edge functions) can read or write.
ALTER TABLE public.upload_starts ENABLE ROW LEVEL SECURITY;
